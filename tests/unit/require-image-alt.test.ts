import { defineMdastPlugin, markdownToHtml } from 'satteri';
import { describe, expect, test } from 'vitest';
import { requireImageAlt } from '../../src/lib/markdown/require-image-alt';

const directory = new URL('file:///blog/posts/');
const fileURL = new URL('post.md', directory);
const mdastPlugins = [requireImageAlt(directory)];

describe('required Markdown image alt text', () => {
  test.each([
    '![](photo.png)',
    '![  ](photo.png)',
    '![][photo]\n\n[photo]: photo.png',
  ])('rejects %s with its file and line', (image) => {
    expect(() =>
      markdownToHtml(`Introduction\n\n${image}`, { fileURL, mdastPlugins }),
    ).toThrow(
      '/blog/posts/post.md (Markdown line 3): Markdown images need non-empty alt text.',
    );
  });

  test.each([
    '<img src="photo.png">',
    'Inline <IMG SRC=photo.png ALT="">',
    '<figure>\n  <img src="photo.png" alt=" &#32; ">\n</figure>',
  ])('rejects authored HTML without alt: %s', (html) => {
    expect(() =>
      markdownToHtml(`Introduction\n\n${html}`, { fileURL, mdastPlugins }),
    ).toThrow(
      '/blog/posts/post.md (Markdown HTML starts on line 3): HTML images need non-empty alt text.',
    );
  });

  test('accepts descriptive alt text and ignores Markdown examples in code', () => {
    const { html } = markdownToHtml(
      '![A mountain](photo.png)\n\n`![](example.png)`',
      {
        fileURL,
        mdastPlugins,
      },
    );
    expect(html).toContain('alt="A mountain"');
  });

  test('accepts HTML alt text and ignores HTML examples and comments', () => {
    const { html } = markdownToHtml(
      '<picture><source srcset="photo.webp"><img src="photo.png" alt="A &gt; B"></picture>\n\n`<img src=x>`\n\n<!-- <img src=x> -->',
      { fileURL, mdastPlugins },
    );
    expect(html).toContain('alt="A &gt; B"');
  });

  test('does not reject decorative images generated by a later plugin', () => {
    const generatedImage = defineMdastPlugin({
      name: 'generated-image',
      paragraph(node, context) {
        context.replaceNode(node, {
          type: 'html',
          value: '<img src="decoration.png" alt="">',
        });
      },
    });
    const { html } = markdownToHtml('Generate an image', {
      fileURL,
      mdastPlugins: [...mdastPlugins, generatedImage],
    });
    expect(html).toContain('alt=""');
  });

  test('does not enforce post requirements outside the configured directories', () => {
    const { html } = markdownToHtml('![](decoration.png)', {
      fileURL: new URL('../standalone.md', directory),
      mdastPlugins,
    });
    expect(html).toContain('alt=""');
  });
});
